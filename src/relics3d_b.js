/** 渐细管（爪、角、根须、把手）：pts=[[x,y,z],...]，半径 r0→r1 */
function taper(key, pts, r0, r1, seg = 10, rs = 6) {
  return G(`b:taper${key}`, () => {
    const curve = new THREE.CatmullRomCurve3(pts.map((v) => new THREE.Vector3(...v)));
    const fr = curve.computeFrenetFrames(seg, false);
    const pos = [], uv = [], idx = [];
    for (let i = 0; i <= seg; i++) {
      const t = i / seg, c = curve.getPointAt(t), r = r0 + (r1 - r0) * t;
      const N = fr.normals[i], B = fr.binormals[i];
      for (let j = 0; j < rs; j++) {
        const a = (j / rs) * TAU, ca = Math.cos(a), sa = Math.sin(a);
        pos.push(c.x + r * (ca * N.x + sa * B.x), c.y + r * (ca * N.y + sa * B.y), c.z + r * (ca * N.z + sa * B.z));
        uv.push(j / rs, t);
      }
    }
    for (let i = 0; i < seg; i++) for (let j = 0; j < rs; j++) {
      const a = i * rs + j, b = i * rs + (j + 1) % rs, c = (i + 1) * rs + j, d = (i + 1) * rs + (j + 1) % rs;
      idx.push(a, b, c, b, d, c);
    }
    const c0 = curve.getPointAt(0), c1 = curve.getPointAt(1);
    const s0 = pos.length / 3; pos.push(c0.x, c0.y, c0.z); uv.push(0.5, 0);
    const s1 = pos.length / 3; pos.push(c1.x, c1.y, c1.z); uv.push(0.5, 1);
    for (let j = 0; j < rs; j++) {
      idx.push(s0, (j + 1) % rs, j);
      idx.push(s1, seg * rs + j, seg * rs + (j + 1) % rs);
    }
    const g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
    g.setAttribute('uv', new THREE.Float32BufferAttribute(uv, 2));
    g.setIndex(idx);
    g.computeVertexNormals();
    return g;
  });
}
const mirrorX = (pts) => pts.map(([x, y, z]) => [-x, y, z]);

/** 齿轮外形（XY 平面），可带圆孔 */
function gearShape(n, ro, ri, hole = 0) {
  const s = new THREE.Shape(), st = TAU / n;
  for (let i = 0; i < n; i++) {
    const a = i * st;
    const q = [[ri, a - 0.27 * st], [ro, a - 0.15 * st], [ro, a + 0.15 * st], [ri, a + 0.27 * st]];
    q.forEach(([r, t], k) => (i === 0 && k === 0 ? s.moveTo : s.lineTo).call(s, r * Math.cos(t), r * Math.sin(t)));
  }
  s.closePath();
  if (hole > 0) { const h = new THREE.Path(); h.absarc(0, 0, hole, 0, TAU, true); s.holes.push(h); }
  return s;
}
const gear = (n, ro, ri, d, hole = 0) => ext(`b:gear${n},${ro},${ri},${d},${hole}`, () => gearShape(n, ro, ri, hole), d, 0.0015, 6);

/** 原作常见的小底座：深铁块 + 木条，返回顶面 y */
function plinth(g, w = 0.18, d = 0.09, h = 0.026, plank = true, x = 0) {
  p(g, box(w, h, d), K.base(), [x, h / 2, 0]);
  if (!plank) return h;
  p(g, box(w * 0.9, 0.007, d * 0.72), K.plank(), [x, h + 0.0035, 0.004]);
  return h + 0.007;
}
/** 正面一组短横线（文字） */
function lines(g, x, yTop, z, widths, gap = 0.016, mat = K.ink(), th = 0.0035) {
  widths.forEach((w, i) => p(g, box(w, th, 0.002), mat, [x, yTop - i * gap, z]));
}
/** 竖立卷轴文书：底在 y0，返回 { g, z: 正面 z } */
function scroll(g, w, h, { knobs = false, rollMat = K.parchL(), sheet = K.parch(), r = 0.011, y0 = 0 } = {}) {
  p(g, box(w, h - r * 2, 0.006), sheet, [0, y0 + h / 2, 0]);
  for (const y of [y0 + r, y0 + h - r]) {
    p(g, cyl(r, r, w + 0.012, 8), rollMat, [0, y, 0.002], [0, 0, PI / 2]);
    if (knobs) for (const sx of [-1, 1]) p(g, sph(r * 0.75, 6, 5), K.copper(), [sx * (w / 2 + 0.014), y, 0.002]);
  }
  return 0.0035;
}
/** 蜡封：圆饼 + 槽，正面朝 +Z */
function seal(g, x, y, z, r, mat, slotMat = K.ink(), rot = 0.5) {
  p(g, cyl(r, r, 0.008, 12), mat, [x, y, z + 0.004], [PI / 2, 0, 0]);
  p(g, tor(r * 0.8, 0.0018, 4, 14), slotMat, [x, y, z + 0.008]);
  p(g, box(0.0035, r * 0.9, 0.003), slotMat, [x, y, z + 0.009], [0, 0, rot]);
}
/** 竖立的书：正面朝 +Z，返回子组与正面 z */
function book(g, { w = 0.15, h = 0.2, d = 0.04, cover, spine, pages = K.parchL() }, pos = [0, 0, 0], rot = [0, 0, 0]) {
  const s = sub(g, pos, rot);
  const c = 0.006;
  p(s, box(w - 0.006, h - 0.01, d - 2 * c), pages, [0.002, h / 2, 0]);
  p(s, box(w, h, c), cover, [0, h / 2, d / 2 - c / 2]);
  p(s, box(w, h, c), cover, [0, h / 2, -d / 2 + c / 2]);
  p(s, box(0.01, h, d), spine ?? cover, [-w / 2 + 0.003, h / 2, 0]);
  return { s, z: d / 2 };
}
/** 书角包铜（正面四角） */
function corners(s, w, h, z, mat, k = 0.024) {
  for (const sx of [-1, 1]) for (const sy of [0, 1]) {
    p(s, box(k, k, 0.004), mat, [sx * (w / 2 - k / 2 + 0.002), sy ? h - k / 2 + 0.002 : k / 2 - 0.002, z + 0.001]);
  }
}

