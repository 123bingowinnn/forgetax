function hourglass(g, streamMat) {
  p(g, box(0.13, 0.02, 0.075), K.base(), [0, 0.01, 0]);
  p(g, box(0.118, 0.007, 0.064), K.plank(), [0, 0.0235, 0]);
  p(g, box(0.13, 0.016, 0.075), K.ironD(), [0, 0.228, 0]);
  for (const sx of [-1, 1]) for (const sz of [-1, 1]) p(g, cyl(0.0045, 0.0045, 0.2, 5), K.wood(), [sx * 0.052, 0.12, sz * 0.026]);
  const prof = [[0.003, 0], [0.034, 0.004], [0.042, 0.02], [0.036, 0.05], [0.016, 0.085], [0.007, 0.096],
    [0.016, 0.107], [0.036, 0.142], [0.042, 0.172], [0.034, 0.188], [0.003, 0.192]];
  // 玻璃：后半不透明暗青，前半半透明，中间的砂流透出来
  const half = (k, ps, pl) => G(`b:hg${k}`, () => new THREE.LatheGeometry(prof.map(([r, y]) => new THREE.Vector2(r, y)), 7, ps, pl));
  p(g, half('back', PI / 2, PI), M(0x2a3a38, { r: 0.35, m: 0.3, tex: false }), [0, 0.027, 0]);
  p(g, half('front', -PI / 2, PI), M(0x34504c, { r: 0.15, m: 0.3, op: 0.6 }), [0, 0.027, 0]);
  p(g, cyl(0.0025, 0.0025, 0.1, 4), streamMat, [0, 0.027 + 0.08, 0]);
  p(g, cyl(0.004, 0.026, 0.02, 8), streamMat, [0, 0.027 + 0.014, 0]);
}

function docSeal(g, x, y, z, mat, ribbonMat) {
  p(g, box(0.016, 0.032, 0.003), ribbonMat, [x, y - 0.024, z + 0.001], [0, 0, 0.12]);
  seal(g, x, y, z, 0.02, mat, K.ink());
}

